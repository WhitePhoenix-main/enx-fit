    public static IReadOnlyList<EquipmentDescription> EquipmentDetails(Exercise exercise)
    {
        if (string.IsNullOrWhiteSpace(exercise.Equipment)) return [];

        var parts = Regex.Split(exercise.Equipment, @"\s*,\s*|\s+или\s+", RegexOptions.IgnoreCase);
        var result = new List<EquipmentDescription>();
        foreach (var part in parts)
        {
            var name = part.Trim();
            if (name.Length == 0 || result.Any(item => item.Name.Equals(name, StringComparison.OrdinalIgnoreCase))) continue;

            if (Equipment.TryGetValue(name, out var description))
            {
                if (name.Equals("Тренажёр", StringComparison.OrdinalIgnoreCase) &&
                    MachineDescriptions.TryGetValue(exercise.Name, out var specific))
                    result.Add(description with { Description = specific });
                else
                    result.Add(description);
            }
        }

        return result;
    }

    public static string EquipmentIcon(Exercise exercise) =>
        EquipmentDetails(exercise).FirstOrDefault()?.Icon ?? "workout";

